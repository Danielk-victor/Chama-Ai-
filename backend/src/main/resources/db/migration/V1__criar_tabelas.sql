-- Chama Aí – Esquema inicial (PostgreSQL 16)
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE cidade (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(100) NOT NULL,
    uf    CHAR(2)      NOT NULL,
    CONSTRAINT uq_cidade UNIQUE (nome, uf)
);

CREATE TABLE categoria (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(60) NOT NULL UNIQUE,
    ativa BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE usuario (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              VARCHAR(120) NOT NULL,
    email             VARCHAR(150) NOT NULL UNIQUE,
    senha_hash        VARCHAR(100) NOT NULL,
    telefone_whatsapp VARCHAR(20)  NOT NULL,
    tipo              VARCHAR(15)  NOT NULL,
    ativo             BOOLEAN      NOT NULL DEFAULT TRUE,
    cidade_id         BIGINT       NOT NULL REFERENCES cidade (id),
    criado_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_tipo CHECK (tipo IN ('CONTRATANTE', 'PRESTADOR', 'ADMIN'))
);

CREATE TABLE perfil_prestador (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT       NOT NULL UNIQUE REFERENCES usuario (id),
    categoria_id    BIGINT       NOT NULL REFERENCES categoria (id),
    cidade_id       BIGINT       NOT NULL REFERENCES cidade (id),
    descricao       TEXT,
    regiao_atendida VARCHAR(200),
    foto_caminho    VARCHAR(255),
    exibir_whatsapp BOOLEAN      NOT NULL DEFAULT TRUE,
    status          VARCHAR(15)  NOT NULL DEFAULT 'RASCUNHO',
    CONSTRAINT ck_perfil_status CHECK (status IN ('RASCUNHO', 'PUBLICADO', 'SUSPENSO'))
);
CREATE INDEX ix_perfil_busca ON perfil_prestador (status, cidade_id, categoria_id);

CREATE TABLE servico (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id     BIGINT        NOT NULL REFERENCES perfil_prestador (id) ON DELETE CASCADE,
    nome          VARCHAR(100)  NOT NULL,
    tipo_cobranca VARCHAR(15)   NOT NULL,
    valor         NUMERIC(10,2),
    ativo         BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_servico_cobranca CHECK (tipo_cobranca IN ('HORA', 'DIARIA', 'FIXO', 'A_COMBINAR')),
    CONSTRAINT ck_servico_valor CHECK (
        (tipo_cobranca = 'A_COMBINAR' AND valor IS NULL) OR (tipo_cobranca <> 'A_COMBINAR' AND valor > 0))
);

CREATE TABLE disponibilidade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id   BIGINT   NOT NULL REFERENCES perfil_prestador (id) ON DELETE CASCADE,
    dia_semana  SMALLINT NOT NULL,
    hora_inicio TIME     NOT NULL,
    hora_fim    TIME     NOT NULL,
    CONSTRAINT ck_disp_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_disp_horas CHECK (hora_fim > hora_inicio)
);
CREATE INDEX ix_disp_perfil ON disponibilidade (perfil_id, dia_semana);

CREATE TABLE documento_identificacao (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id        BIGINT       NOT NULL REFERENCES perfil_prestador (id),
    tipo_documento   VARCHAR(10)  NOT NULL,
    caminho_arquivo  VARCHAR(255) NOT NULL,
    status           VARCHAR(15)  NOT NULL DEFAULT 'EM_ANALISE',
    motivo_rejeicao  VARCHAR(300),
    enviado_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    analisado_em     TIMESTAMPTZ,
    analisado_por    BIGINT REFERENCES usuario (id),
    consentimento_em TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_doc_tipo CHECK (tipo_documento IN ('RG', 'CNH', 'OUTRO')),
    CONSTRAINT ck_doc_status CHECK (status IN ('EM_ANALISE', 'APROVADO', 'REJEITADO')),
    CONSTRAINT ck_doc_rejeicao CHECK (status <> 'REJEITADO' OR motivo_rejeicao IS NOT NULL)
);
CREATE INDEX ix_doc_status ON documento_identificacao (status, enviado_em);

CREATE TABLE agendamento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id      BIGINT       NOT NULL REFERENCES perfil_prestador (id),
    contratante_id BIGINT       NOT NULL REFERENCES usuario (id),
    servico_id     BIGINT       NOT NULL REFERENCES servico (id),
    data           DATE         NOT NULL,
    hora_inicio    TIME         NOT NULL,
    hora_fim       TIME         NOT NULL,
    observacoes    VARCHAR(500),
    status         VARCHAR(15)  NOT NULL DEFAULT 'PENDENTE',
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_agend_status CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'RECUSADO', 'CANCELADO', 'CONCLUIDO')),
    CONSTRAINT ck_agend_horas CHECK (hora_fim > hora_inicio),
    -- RN05: dois agendamentos confirmados do mesmo prestador não podem se sobrepor
    CONSTRAINT ex_agendamento_sem_conflito EXCLUDE USING gist (
        perfil_id WITH =,
        tsrange(data + hora_inicio, data + hora_fim) WITH &&
    ) WHERE (status = 'CONFIRMADO')
);
CREATE INDEX ix_agend_prestador ON agendamento (perfil_id, data);
CREATE INDEX ix_agend_contratante ON agendamento (contratante_id, data);

CREATE TABLE avaliacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agendamento_id BIGINT      NOT NULL UNIQUE REFERENCES agendamento (id),
    nota           SMALLINT    NOT NULL,
    comentario     VARCHAR(500),
    criado_em      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_avaliacao_nota CHECK (nota BETWEEN 1 AND 5)
);
